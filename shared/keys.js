export function keyToVk(name) {
  if (typeof name !== 'string') return null;
  const n = name.toLowerCase();
  return VK[n] ?? null;
}

export const COMBO_PRESETS = Object.freeze({
  copy: ['ctrl', 'c'],
  paste: ['ctrl', 'v'],
  cut: ['ctrl', 'x'],
  selectall: ['ctrl', 'a'],
  undo: ['ctrl', 'z'],
  redo: ['ctrl', 'y'],
  save: ['ctrl', 's'],
  find: ['ctrl', 'f'],
  close: ['alt', 'f4'],
  taskmanager: ['ctrl', 'shift', 'escape'],
  switchapp: ['alt', 'tab'],
  lock: ['lwin', 'l'],
  browser: ['lwin', 'e'],
  screenshot: ['lwin', 'shift', 's'],
});

export function resolveCombo(name) {
  if (typeof name !== 'string') return null;
  return COMBO_PRESETS[name.toLowerCase()] ?? null;
}